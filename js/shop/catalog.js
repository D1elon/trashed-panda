export const IMG = new URL('../../assets/shop/', import.meta.url).href;

export function productById(id) {
  return PRODUCTS.find((p) => p.id === id);
}

/** Default option selection: first value of every option. */
export function defaultOptions(p) {
  const o = {};
  for (const [k, vals] of Object.entries(p.options)) o[k] = typeof vals[0] === 'string' ? vals[0] : vals[0].value;
  return o;
}

/** The option that drives the picture (Color or Design), if any. */
export function visualOption(p) {
  return Object.keys(p.options).find((k) => typeof p.options[k][0] === 'object');
}

function selectedVisual(p, options) {
  const key = visualOption(p);
  if (!key) return null;
  const val = options[key] ?? p.options[key][0].value;
  return p.options[key].find((o) => o.value === val) ?? p.options[key][0];
}

/** Every picture for the current selection: [{ label, src, bg, flat }]. */
export function viewsFor(p, options = {}) {
  const opt = selectedVisual(p, options);
  const views = opt ? opt.views : p.views;
  const bg = opt ? opt.bg : p.bg;
  return views.map((v) => ({ label: v.label, src: IMG + v.src, bg: v.bg || bg, flat: Boolean(v.flat) }));
}

/** The main picture (card, cart line, option button). */
export function imageFor(p, options = {}) {
  return viewsFor(p, options)[0];
}

/** Options worth showing on a cart line: skip ones with a single fixed value. */
export function variantLabel(p, options) {
  return Object.entries(options)
    .filter(([k]) => (p.options[k]?.length ?? 0) > 1)
    .map(([, v]) => v)
    .join(' / ');
}

export function formatPrice(n) {
  return new Intl.NumberFormat('en-US', { style: 'currency', currency: STORE.currency, minimumFractionDigits: n % 1 ? 2 : 0 }).format(n);
}
